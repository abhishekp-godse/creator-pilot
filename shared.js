const THEMES = {
  obsidian: { name: 'Obsidian Glass', icon: '🌌', label: 'Obsidian' },
  cyberpunk: { name: 'Cyberpunk Neon', icon: '⚡', label: 'Cyber' },
  aurora: { name: 'Aurora Ambient', icon: '🌿', label: 'Aurora' },
  minimal: { name: 'Minimalist Pro', icon: '✨', label: 'Minimal' }
};

let currentTheme = localStorage.getItem('creatorpilot_theme') || 'obsidian';

function ensureSharedCssLoaded() {
  if (!document.querySelector('link[href*="shared.css"]')) {
    const link = document.createElement('link');
    link.rel = 'stylesheet';
    link.href = 'shared.css';
    document.head.appendChild(link);
  }
}

function initThemeEngine() {
  ensureSharedCssLoaded();
  const saved = localStorage.getItem('creatorpilot_theme') || 'obsidian';
  setTheme(saved, false);
}

function setTheme(themeKey, notify = true) {
  if (!THEMES[themeKey]) themeKey = 'obsidian';
  currentTheme = themeKey;
  localStorage.setItem('creatorpilot_theme', themeKey);

  // Update body classes
  document.body.classList.remove('theme-obsidian', 'theme-cyberpunk', 'theme-aurora', 'theme-minimal');
  document.body.classList.add(`theme-${themeKey}`);

  // Update any theme buttons in the DOM
  document.querySelectorAll('.cp-theme-btn').forEach(btn => {
    const target = btn.getAttribute('data-theme');
    if (target === themeKey) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  if (notify && typeof showToast === 'function') {
    showToast(`🎨 Theme: ${THEMES[themeKey].icon} ${THEMES[themeKey].name} Active`, 'success');
  }

  // Dispatch global event for pages that have custom canvas/charts
  window.dispatchEvent(new CustomEvent('creatorpilot_theme_changed', { detail: { theme: themeKey } }));
}

function injectThemePickerInNavbar() {
  // Check if already injected
  if (document.getElementById('cpGlobalThemePicker')) return;

  const targetContainer = document.getElementById('authHeaderArea') || 
                          document.querySelector('header .flex.items-center.gap-2\\.5') || 
                          document.querySelector('header .flex.items-center:last-child') ||
                          document.querySelector('aside .p-5');

  if (!targetContainer) return;

  const picker = document.createElement('div');
  picker.id = 'cpGlobalThemePicker';
  picker.className = 'cp-theme-picker hidden sm:flex items-center';
  picker.title = 'Switch CreatorPilot UI Theme';
  picker.innerHTML = `
    <button onclick="setTheme('obsidian')" data-theme="obsidian" class="cp-theme-btn ${currentTheme === 'obsidian' ? 'active' : ''}">
      <span>🌌</span> <span class="hidden xl:inline">Obsidian</span>
    </button>
    <button onclick="setTheme('cyberpunk')" data-theme="cyberpunk" class="cp-theme-btn ${currentTheme === 'cyberpunk' ? 'active' : ''}">
      <span>⚡</span> <span class="hidden xl:inline">Cyber</span>
    </button>
    <button onclick="setTheme('aurora')" data-theme="aurora" class="cp-theme-btn ${currentTheme === 'aurora' ? 'active' : ''}">
      <span>🌿</span> <span class="hidden xl:inline">Aurora</span>
    </button>
    <button onclick="setTheme('minimal')" data-theme="minimal" class="cp-theme-btn ${currentTheme === 'minimal' ? 'active' : ''}">
      <span>✨</span> <span class="hidden xl:inline">Minimal</span>
    </button>
  `;

  // Insert before the auth container if found, or prepend into the header controls
  if (targetContainer.id === 'authHeaderArea') {
    targetContainer.parentNode.insertBefore(picker, targetContainer);
  } else if (targetContainer.firstChild) {
    targetContainer.insertBefore(picker, targetContainer.firstChild);
  } else {
    targetContainer.appendChild(picker);
  }
}

