// Global App State & Storage Management
let activeCreator = CREATOR_PROFILES.codecraft;
let isLoggedIn = true;

function getActiveProfile() {
  try {
    const saved = JSON.parse(localStorage.getItem('creatorpilot_auth'));
    if (saved) {
      isLoggedIn = (saved.isLoggedIn !== false);
      if (saved.profileKey && CREATOR_PROFILES[saved.profileKey]) {
        const p = CREATOR_PROFILES[saved.profileKey];
        if (saved.ownerName) p.ownerName = saved.ownerName;
        if (saved.loginId) p.loginId = saved.loginId;
        return p;
      }
    }
  } catch(e) {}
  return CREATOR_PROFILES.codecraft;
}

function setActiveProfile(key, customName, customId) {
  const profile = CREATOR_PROFILES[key] || CREATOR_PROFILES.codecraft;
  if (customName) profile.ownerName = customName;
  if (customId) profile.loginId = customId;
  activeCreator = profile;
  isLoggedIn = true;
  localStorage.setItem('creatorpilot_auth', JSON.stringify({
    isLoggedIn: true,
    profileKey: key,
    ownerName: profile.ownerName,
    loginId: profile.loginId,
    userId: profile.userId
  }));
  updateAuthPortalSession(profile, true);
  return profile;
}

